@Composable
internal fun rememberAppTypography(screenSize: ScreenSize): androidx.compose.material3.Typography {
    return remember(screenSize) {
        if (screenSize == ScreenSize.TABLET) {
            tabletTypography
        } else {
            phoneTypography
        }
    }
}
